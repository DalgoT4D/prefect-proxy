@pytest.mark.asyncio
async def test_postgres_executes_generated_sql():
    mock_conn = MagicMock()
    mock_cursor = MagicMock()
    mock_conn.cursor.return_value.__enter__ = lambda s: mock_cursor
    mock_conn.cursor.return_value.__exit__ = MagicMock(return_value=False)

    with patch("proxy.prefect_flows_runner.Secret") as mock_secret, patch(
        "psycopg2.connect", return_value=mock_conn
    ) as mock_connect:
        mock_secret.aload = AsyncMock(return_value=_secret_block("postgres", POSTGRES_CREDS))
        await _run_post_sync_ops(
            env={"dbt-profile-secret-block": "my-block"},
            ops=[
                {
                    "type": "cast",
                    "schema": "dest",
                    "table": "orders",
                    "column_casts": {"amount": "numeric"},
                }
            ],
        )

    mock_connect.assert_called_once_with(
        host="localhost",
        port=5432,
        dbname="mydb",
        user="myuser",
        password="secret",
    )
    # Exactly one ALTER TABLE statement was executed
    mock_cursor.execute.assert_called_once()
    executed_sql = mock_cursor.execute.call_args.args[0]
    assert 'ALTER TABLE "dest"."orders"' in executed_sql
    assert 'ALTER COLUMN "amount" TYPE numeric' in executed_sql
    mock_conn.close.assert_called_once()


