def test_bigquery_single_cast_no_partition():
    sql = _build_bigquery_cast_sql(
        "my-project", "dest", "orders", {"amount": "numeric"}, _bq_table_meta()
    )
    assert "CREATE OR REPLACE TABLE `my-project`.`dest`.`orders`" in sql
    assert "PARTITION BY" not in sql
    assert "CLUSTER BY" not in sql
    assert "SELECT * REPLACE" in sql
    assert "CAST(`amount` AS NUMERIC) AS `amount`" in sql


def test_bigquery_with_partition_and_cluster():
    """The Airbyte-standard spec: DAY partition on _airbyte_extracted_at, cluster on same."""
    meta = _bq_table_meta(
        partition_field="_airbyte_extracted_at",
        partition_type="DAY",
        cluster_fields=["_airbyte_extracted_at"],
    )
    sql = _build_bigquery_cast_sql("my-project", "dest", "orders", {"amount": "numeric"}, meta)
    assert "PARTITION BY DATE(`_airbyte_extracted_at`)" in sql
    assert "CLUSTER BY `_airbyte_extracted_at`" in sql
    assert "CAST(`amount` AS NUMERIC) AS `amount`" in sql


def test_bigquery_cluster_with_primary_keys():
    meta = _bq_table_meta(
        partition_field="_airbyte_extracted_at",
        partition_type="DAY",
        cluster_fields=["_airbyte_extracted_at", "id", "order_id"],
    )
    sql = _build_bigquery_cast_sql("my-project", "dest", "orders", {"amount": "numeric"}, meta)
    assert "CLUSTER BY `_airbyte_extracted_at`, `id`, `order_id`" in sql


def test_bigquery_partition_type_hour():
    meta = _bq_table_meta(partition_field="ts", partition_type="HOUR")
    sql = _build_bigquery_cast_sql("proj", "s", "t", {"col": "numeric"}, meta)
    assert "PARTITION BY TIMESTAMP_TRUNC(`ts`, HOUR)" in sql


def test_bigquery_unknown_partition_type_skipped():
    """If we don't know the partition type, we skip PARTITION BY (safer than emitting bad SQL)."""
    meta = _bq_table_meta(partition_field="ts", partition_type="WEEK")
    sql = _build_bigquery_cast_sql("proj", "s", "t", {"col": "numeric"}, meta)
    assert "PARTITION BY" not in sql


def test_bigquery_column_name_normalized():
    sql = _build_bigquery_cast_sql("proj", "s", "t", {"Measure 7": "numeric"}, _bq_table_meta())
    assert "CAST(`Measure_7` AS NUMERIC) AS `Measure_7`" in sql


def test_bigquery_unknown_type_raises():
    with pytest.raises(ValueError, match="Unsupported cast type for BigQuery"):
        _build_bigquery_cast_sql("proj", "s", "t", {"col": "STRUCT"}, _bq_table_meta())


