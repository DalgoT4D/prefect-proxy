"""Unit tests for _run_post_sync_ops() + SQL builder helpers in proxy/prefect_flows_runner.py.

SQL is now built inside prefect-proxy from raw op config (not pre-generated by
backend). BigQuery uses live table metadata (partition/cluster spec) to build
CREATE OR REPLACE that Airbyte-partitioned tables will accept.
"""
import json
from unittest.mock import AsyncMock, MagicMock, patch

import pytest

from proxy.prefect_flows_runner import (
    _build_bigquery_cast_sql,
    _build_postgres_cast_sql,
    _normalize_column_name,
    _run_post_sync_ops,
)


POSTGRES_CREDS = {
    "host": "localhost",
    "port": 5432,
    "database": "mydb",
    "user": "myuser",
    "password": "secret",
}

BIGQUERY_CREDS = {
    "type": "service_account",
    "project_id": "my-project",
    "private_key_id": "key-id",
    "private_key": "key",
    "client_email": "svc@my-project.iam.gserviceaccount.com",
    "client_id": "123",
    "auth_uri": "https://accounts.google.com/o/oauth2/auth",
    "token_uri": "https://oauth2.googleapis.com/token",
}


def _secret_block(wtype: str, creds: dict):
    block = MagicMock()
    block.get.return_value = json.dumps({"wtype": wtype, "creds": creds})
    return block


def _bq_table_meta(partition_field=None, partition_type="DAY", cluster_fields=None):
    """Simulate a google.cloud.bigquery.Table result from client.get_table()."""
    meta = MagicMock()
    if partition_field:
        meta.time_partitioning = MagicMock(field=partition_field, type_=partition_type)
    else:
        meta.time_partitioning = None
    meta.clustering_fields = cluster_fields
    return meta


