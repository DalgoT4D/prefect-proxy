def test_postgres_single_cast():
    sql = _build_postgres_cast_sql("dest", "orders", {"amount": "numeric"})
    assert (
        sql
        == 'ALTER TABLE "dest"."orders"\n  ALTER COLUMN "amount" TYPE numeric USING "amount"::numeric'
    )


def test_postgres_multiple_casts():
    sql = _build_postgres_cast_sql(
        "dest", "orders", {"amount": "numeric", "created_at": "timestamp"}
    )
    assert '"amount"' in sql
    assert '"created_at"' in sql
    assert "ALTER TABLE" in sql


def test_postgres_column_name_normalized():
    """Column names with spaces get underscored to match Airbyte's destination convention."""
    sql = _build_postgres_cast_sql("dest", "orders", {"Measure 7": "numeric"})
    assert '"Measure_7"' in sql
    assert '"Measure 7"' not in sql


def test_postgres_unknown_type_raises():
    with pytest.raises(ValueError, match="Unsupported cast type for Postgres"):
        _build_postgres_cast_sql("s", "t", {"col": "jsonb"})


