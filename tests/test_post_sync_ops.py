@pytest.mark.asyncio
async def test_bigquery_fetches_metadata_and_executes():
    """Verify: get_table is called, generated SQL includes partition/cluster
    from the live metadata, and client.close() runs afterwards."""
    mock_client = MagicMock()
    mock_client.get_table.return_value = _bq_table_meta(
        partition_field="_airbyte_extracted_at",
        partition_type="DAY",
        cluster_fields=["_airbyte_extracted_at"],
    )
    mock_query_job = MagicMock()
    mock_client.query.return_value = mock_query_job

    with patch("proxy.prefect_flows_runner.Secret") as mock_secret, patch(
        "google.oauth2.service_account.Credentials.from_service_account_info"
    ), patch("google.cloud.bigquery.Client", return_value=mock_client):
        mock_secret.aload = AsyncMock(return_value=_secret_block("bigquery", BIGQUERY_CREDS))
        await _run_post_sync_ops(
            env={"dbt-profile-secret-block": "my-block"},
            ops=[
                {
                    "type": "cast",
                    "schema": "dest",
                    "table": "orders",
                    "column_casts": {"amount": "numeric"},
                }
            ],
        )

    mock_client.get_table.assert_called_once_with("my-project.dest.orders")
    mock_client.query.assert_called_once()
    executed_sql = mock_client.query.call_args.args[0]
    assert "CREATE OR REPLACE TABLE `my-project`.`dest`.`orders`" in executed_sql
    assert "PARTITION BY DATE(`_airbyte_extracted_at`)" in executed_sql
    assert "CLUSTER BY `_airbyte_extracted_at`" in executed_sql
    assert "CAST(`amount` AS NUMERIC) AS `amount`" in executed_sql
    mock_query_job.result.assert_called_once()
    mock_client.close.assert_called_once()


